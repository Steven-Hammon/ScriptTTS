"""Tk layout, kept separate from the reader controls and background work."""
import tkinter as tk
from tkinter import ttk

from .config import MODELS, Settings
from .engine import KOKORO_PRESETS

LANGUAGES = ("English", "Auto", "Chinese", "Japanese", "Korean", "German", "French", "Russian", "Portuguese", "Spanish", "Italian")


def build(self):
    style = ttk.Style()
    style.theme_use("clam")
    style.configure("TFrame", background="#f3f5f8")
    style.configure("TLabel", background="#f3f5f8", foreground="#18263b", font=("Segoe UI", 10))
    style.configure("Title.TLabel", font=("Segoe UI", 23, "bold"))
    style.configure("Sub.TLabel", foreground="#5d6c81", font=("Segoe UI", 10))
    style.configure("Field.TLabel", font=("Segoe UI", 10, "bold"))
    style.configure("Status.TLabel", foreground="#18263b", font=("Segoe UI", 11))
    style.configure("Loading.TLabel", foreground="#8b1e22", font=("Segoe UI", 11, "bold"))
    style.configure("Ready.TLabel", foreground="#14532d", font=("Segoe UI", 11, "bold"))
    style.configure("TButton", font=("Segoe UI", 10), padding=(10, 6))
    style.configure("TEntry", padding=7, fieldbackground="white", font=("Segoe UI", 11))
    style.configure("TCombobox", padding=6)
    style.configure("TCheckbutton", background="#f3f5f8", font=("Segoe UI", 10))
    panel = ttk.Frame(self.root, padding=22)
    panel.pack(fill="both", expand=True)
    panel.columnconfigure(0, weight=1)
    panel.rowconfigure(2, weight=1)
    ttk.Label(panel, text="ScriptTTS", style="Title.TLabel").grid(row=0, column=0, sticky="w")
    ttk.Label(panel, text="Read along with the sound. Keep your place.", style="Sub.TLabel").grid(row=1, column=0, sticky="w", pady=(3, 14))
    tabs = ttk.Notebook(panel)
    tabs.grid(row=2, column=0, sticky="nsew")
    reader = ttk.Frame(tabs, padding=16)
    voice = ttk.Frame(tabs, padding=16)
    tabs.add(reader, text="Reader")
    tabs.add(voice, text="Voice settings")
    tabs.bind("<<NotebookTabChanged>>", self._hotkey_tab_changed)
    for page in (reader, voice):
        page.columnconfigure(0, weight=1)

    ttk.Label(reader, text="Start / stop hotkey", style="Field.TLabel").grid(row=0, column=0, sticky="w")
    self.hotkey_text = tk.StringVar(value=self.settings.hotkey_label.upper())
    self.hotkey_entry = ttk.Entry(reader, textvariable=self.hotkey_text, state="readonly", takefocus=False)
    self.hotkey_entry.grid(row=1, column=0, sticky="ew", pady=(5, 4))
    for sequence, handler in (("<FocusIn>", self._hotkey_focus_in), ("<Button-1>", self._record_start), ("<KeyPress>", self._record_key), ("<FocusOut>", self._record_leave)):
        self.hotkey_entry.bind(sequence, handler)
    self.root.bind("<Button-1>", self._hotkey_outside_click, add="+")
    ttk.Label(reader, text="Click the field and press a shortcut with Ctrl or Alt.", style="Sub.TLabel").grid(row=2, column=0, sticky="w", pady=(0, 12))
    ttk.Label(reader, text="Speech model", style="Field.TLabel").grid(row=3, column=0, sticky="w")
    models = ttk.Frame(reader)
    models.grid(row=4, column=0, sticky="ew", pady=(5, 12))
    models.columnconfigure(0, weight=1)
    self.model_label = tk.StringVar(value=MODELS[self.settings.model].label)
    self.model_box = ttk.Combobox(models, textvariable=self.model_label, values=tuple(spec.label for spec in MODELS.values()), state="readonly")
    self.model_box.grid(row=0, column=0, sticky="ew", padx=(0, 8))
    self.model_box.bind("<<ComboboxSelected>>", self._model_changed)
    self.prepare_button = ttk.Button(models, text="Prepare model", command=self._prepare_model)
    self.prepare_button.grid(row=0, column=1)
    self.normalize = tk.BooleanVar(value=self.settings.normalize_text)
    self.use_ollama = tk.BooleanVar(value=self.settings.ollama_enabled)
    flags = ttk.Frame(reader)
    flags.grid(row=5, column=0, sticky="ew", pady=(0, 10))
    ttk.Checkbutton(flags, text="Sentence case + spoken numbers", variable=self.normalize).pack(side="left")
    ttk.Checkbutton(flags, text="Use Ollama cleanup", variable=self.use_ollama).pack(side="left", padx=(14, 0))
    ttk.Label(reader, text="Local Ollama model", style="Field.TLabel").grid(row=6, column=0, sticky="w")
    ollama = ttk.Frame(reader)
    ollama.grid(row=7, column=0, sticky="ew", pady=(5, 6))
    ollama.columnconfigure(0, weight=1)
    self.ollama_model = tk.StringVar(value=self.settings.ollama_model)
    self.ollama_box = ttk.Combobox(ollama, textvariable=self.ollama_model, state="readonly")
    self.ollama_box.grid(row=0, column=0, sticky="ew", padx=(0, 8))
    self.refresh_button = ttk.Button(ollama, text="Refresh", command=self._refresh_ollama)
    self.refresh_button.grid(row=0, column=1)
    ttk.Label(reader, text="Cleanup runs ahead of speech. It changes only what is spoken, never the document.", style="Sub.TLabel", wraplength=650).grid(row=8, column=0, sticky="w", pady=(0, 12))
    actions = ttk.Frame(reader)
    actions.grid(row=9, column=0, sticky="ew", pady=(0, 8))
    self.load_button = ttk.Button(actions, text="Load Models", command=self._load_models)
    self.load_button.pack(side="left")
    self.stop_button = ttk.Button(actions, text="Stop", command=lambda: self.reader.stop(), state="disabled")
    self.stop_button.pack(side="left", padx=8)
    self.cues = tk.BooleanVar(value=self.settings.cues_enabled)
    ttk.Checkbutton(actions, text="Start / stop sounds", variable=self.cues).pack(side="right")
    ttk.Separator(reader).grid(row=10, column=0, sticky="ew", pady=10)
    ttk.Label(reader, text="Current sentence in the document", style="Field.TLabel").grid(row=11, column=0, sticky="w")
    self.current = tk.StringVar(value="LibreOffice / Notepad: place the caret. Chrome PDF: select the first letter.")
    self.current_label = ttk.Label(reader, textvariable=self.current, wraplength=640)
    self.current_label.grid(row=12, column=0, sticky="nw", pady=(5, 12))
    ttk.Label(reader, text="Spoken version", style="Field.TLabel").grid(row=13, column=0, sticky="w")
    self.spoken = tk.StringVar(value="The prepared sentence will appear here when its audio starts.")
    self.spoken_label = ttk.Label(reader, textvariable=self.spoken, style="Sub.TLabel", wraplength=640)
    self.spoken_label.grid(row=14, column=0, sticky="nw", pady=(5, 0))
    reader.rowconfigure(15, weight=1)

    ttk.Label(voice, text="Voice sample (.wav)", style="Field.TLabel").grid(row=0, column=0, sticky="w")
    files = ttk.Frame(voice)
    files.grid(row=1, column=0, sticky="ew", pady=(6, 4))
    files.columnconfigure(0, weight=1)
    self.wav = tk.StringVar(value=self.settings.wav)
    self.wav_entry = ttk.Entry(files, textvariable=self.wav)
    self.wav_entry.grid(row=0, column=0, sticky="ew", padx=(0, 8))
    self.browse_button = ttk.Button(files, text="Browse…", command=self._browse)
    self.browse_button.grid(row=0, column=1)
    ttk.Label(voice, text="For Qwen cloning: use a clean 3–15 second sample.", style="Sub.TLabel").grid(row=2, column=0, sticky="w", pady=(0, 18))
    ttk.Label(voice, text="Sample transcript (optional)", style="Field.TLabel").grid(row=3, column=0, sticky="w")
    self.transcript = tk.StringVar(value=self.settings.transcript)
    self.transcript_entry = ttk.Entry(voice, textvariable=self.transcript)
    self.transcript_entry.grid(row=4, column=0, sticky="ew", pady=(6, 18))
    ttk.Label(voice, text="Voice description", style="Field.TLabel").grid(row=5, column=0, sticky="w")
    self.description = tk.StringVar(value=self.settings.description)
    self.description_entry = ttk.Entry(voice, textvariable=self.description)
    self.description_entry.grid(row=6, column=0, sticky="ew", pady=(6, 18))
    ttk.Label(voice, text="Preset voice", style="Field.TLabel").grid(row=7, column=0, sticky="w")
    self.preset = tk.StringVar(value=self.settings.preset)
    self.qwen_speaker = tk.StringVar(value=self.settings.qwen_speaker)
    self.preset_box = ttk.Combobox(voice, textvariable=self.preset, values=KOKORO_PRESETS, state="readonly")
    self.preset_box.grid(row=8, column=0, sticky="ew", pady=(6, 18))
    ttk.Label(voice, text="Reading language", style="Field.TLabel").grid(row=9, column=0, sticky="w")
    self.language = tk.StringVar(value=self.settings.language)
    ttk.Combobox(voice, textvariable=self.language, values=LANGUAGES, state="readonly").grid(row=10, column=0, sticky="ew", pady=(6, 18))
    ttk.Label(voice, text="Kokoro speed · 0.5×–2.0×", style="Field.TLabel").grid(row=11, column=0, sticky="w")
    speed = ttk.Frame(voice)
    speed.grid(row=12, column=0, sticky="ew", pady=(6, 18))
    self.speed = tk.DoubleVar(value=self.settings.speed)
    self.speed_text = tk.StringVar(value=f"{self.settings.speed:.2f}×")
    self.speed_slider = ttk.Scale(speed, from_=0.5, to=2.0, variable=self.speed)
    self.speed_slider.pack(side="left", fill="x", expand=True)
    ttk.Label(speed, textvariable=self.speed_text, width=6).pack(side="right", padx=(10, 0))
    self.backend_hint = tk.StringVar()
    ttk.Label(voice, textvariable=self.backend_hint, style="Sub.TLabel", wraplength=640).grid(row=13, column=0, sticky="w")

    self.status = tk.StringVar(value="Choose Load Models to prepare everything before reading.")
    self.status_label = ttk.Label(panel, textvariable=self.status, style="Status.TLabel", wraplength=680)
    self.status_label.grid(row=3, column=0, sticky="ew", pady=(14, 0))
    panel.bind("<Configure>", lambda event: [label.configure(wraplength=max(300, event.width - 80)) for label in (self.current_label, self.spoken_label, self.status_label)])
    for var in (self.wav, self.transcript, self.language, self.description, self.speed, self.preset, self.qwen_speaker, self.normalize, self.use_ollama, self.ollama_model, self.cues):
        var.trace_add("write", self._settings_changed)
